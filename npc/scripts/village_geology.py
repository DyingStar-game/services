#!/usr/bin/env python3
"""Find the rock each village stands on (ADR services/0008).

The planet's biome regions are drawn in QGIS and exported for Godot as a
populate part (`<planet>_chunks/parts/biomes.dsmpart`). A region carries its
`rock_type` and `clarity`. The game resolves a point with "first matching zone
wins" over the records of its HEALPix tile; this script does the same for every
POI of config/world/<planet>/poi.json, with the DyingStar repository's own
reader and geometry helpers, and writes

  config/world/<planet>/village_geology.json

with each village's biome, rock and clarity, plus the catalogue entries
(rocks.json) of the rocks found. The file is committed: services does not need
the DyingStar repository to build.

  python3 scripts/village_geology.py [--dyingstar ../../DyingStar] [--planet tarsis_3]
  python3 scripts/village_geology.py --check   # compare with the committed file

Needs numpy (DyingStar's healpix_utils).
"""

import argparse
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load_dyingstar(repo):
    tools = repo / "tools/planettech/qgis"
    if not tools.is_dir():
        sys.exit(f"{tools} not found: pass --dyingstar <path to the DyingStar repository>")
    sys.path.insert(0, str(tools))
    from export.planet import dsmp, modifier_geom  # noqa: E402  (path set above)
    return dsmp, modifier_geom


def decode_populate(dsmp, data, strings):
    """Yield (biome, coverage, props, ring) for each record of a tile."""
    off = 0
    sid = lambda i: None if i == dsmp.SID_NONE else strings[i]
    while off < len(data):
        biome_sid, coverage, prop_count, _index, vertex_count, _rsv = struct.unpack_from("<HBBiHH", data, off)
        off += 12
        props = {}
        for _ in range(prop_count):
            key, vtype, _pad = struct.unpack_from("<HBB", data, off)
            if vtype == dsmp.VTYPE_SID:
                value = sid(struct.unpack_from("<I", data, off + 4)[0])
            elif vtype == dsmp.VTYPE_F32:
                value = struct.unpack_from("<f", data, off + 4)[0]
            else:
                value = struct.unpack_from("<i", data, off + 4)[0]
            props[sid(key)] = value
            off += 8
        ring = []
        if coverage == dsmp.COVERAGE_POINT:
            off += 8
        elif coverage == dsmp.COVERAGE_PARTIAL:
            for _ in range(vertex_count):
                lon, lat = struct.unpack_from("<ii", data, off)
                ring.append((lon * dsmp.COORD_SCALE, lat * dsmp.COORD_SCALE))
                off += 8
        yield sid(biome_sid), coverage, props, ring


def rock_at(dsmp, geom, part, strings, lon, lat):
    """First zone with a rock containing (lon, lat), at the finest level."""
    nside, tiles = max(part["levels"], key=lambda lv: lv[0])
    ipix = geom.pix_of(nside, lon, lat)
    payload = dict(tiles).get(ipix)
    if payload is None:
        return None
    count, data = dsmp.split_part_tile(payload)
    for biome, coverage, props, ring in decode_populate(dsmp, data, strings):
        if coverage == dsmp.COVERAGE_POINT:
            continue
        if coverage == dsmp.COVERAGE_PARTIAL and not geom.point_in_ring(lon, lat, ring):
            continue
        if props.get("rock_type"):
            return {"biome": biome, "rock_type": props["rock_type"], "clarity": props.get("clarity")}
    return None


def build(args):
    dsmp, geom = load_dyingstar(args.dyingstar)
    export = args.dyingstar / "assets/qgis/export" / f"{args.planet}_chunks/parts"
    part = dsmp.read_container(str(export / "biomes.dsmpart"))
    strings = json.loads((export / "strings.json").read_text())
    catalogue = json.loads((args.dyingstar / "assets/_universe/_shared/materials/rocks.json").read_text())["rocks"]
    pois = json.loads((ROOT / f"config/world/{args.planet}/poi.json").read_text())["pois"]

    villages = {}
    for p in sorted(pois, key=lambda p: p["name"]):
        found = rock_at(dsmp, geom, part, strings, p["lon"], p["lat"])
        villages[p["name"]] = {"poi_type": p["poi_type"], **(found or {"biome": None, "rock_type": None, "clarity": None})}
    used = sorted({v["rock_type"] for v in villages.values() if v["rock_type"]})
    return {
        "_note": f"GENERATED by npc/scripts/village_geology.py from DyingStar biomes.dsmpart and rocks.json ({args.planet}) — do not edit.",
        "planet": args.planet,
        "data_version": part["manifest"].get("fingerprint"),
        "villages": villages,
        "rocks": {slug: catalogue[slug] for slug in used},
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dyingstar", type=Path, default=ROOT.parent.parent / "DyingStar")
    ap.add_argument("--planet", default="tarsis_3")
    ap.add_argument("--check", action="store_true", help="fail if the committed file is stale or a mining village has no rock")
    args = ap.parse_args()

    out = ROOT / f"config/world/{args.planet}/village_geology.json"
    geology = build(args)
    missing = [n for n, v in geology["villages"].items() if v["poi_type"] == "mining village" and not v["rock_type"]]
    by_rock = {}
    for n, v in geology["villages"].items():
        by_rock.setdefault((v["poi_type"], v["rock_type"]), []).append(n)
    for (kind, rock), names in sorted(by_rock.items(), key=lambda kv: (kv[0][0], str(kv[0][1]))):
        print(f"{kind:16} {str(rock):18} {len(names):3}")
    if missing:
        print(f"mining villages without a rock: {', '.join(missing)}", file=sys.stderr)
    text = json.dumps(geology, indent=2, ensure_ascii=False, sort_keys=False) + "\n"
    if args.check:
        stale = not out.exists() or out.read_text() != text
        if stale:
            print(f"{out.relative_to(ROOT)} is stale: rerun without --check", file=sys.stderr)
        return 1 if (stale or missing) else 0
    out.write_text(text)
    print(f"wrote {out.relative_to(ROOT)}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
